CREATE TABLE disasters (
    disaster_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    type VARCHAR(50),
    severity severity_level NOT NULL,
    active_period DATERANGE,
    status disaster_status NOT NULL DEFAULT 'active',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_disasters PRIMARY KEY (disaster_id)
);

CREATE TABLE zones (
    zone_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    disaster_id INTEGER NOT NULL,
    name VARCHAR(100) NOT NULL,
    severity severity_level NOT NULL,
    primary_shelter_id INTEGER,
    coordinator_contact VARCHAR(20),
    CONSTRAINT pk_zones PRIMARY KEY (zone_id),
    CONSTRAINT fk_zones_disaster
        FOREIGN KEY (disaster_id)
        REFERENCES disasters (disaster_id)
        ON DELETE RESTRICT
);

CREATE TABLE shelters (
    shelter_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    location coordinates,
    capacity INTEGER NOT NULL,
    current_occupancy INTEGER NOT NULL DEFAULT 0,
    status shelter_status NOT NULL DEFAULT 'operational',
    CONSTRAINT pk_shelters PRIMARY KEY (shelter_id)
);

ALTER TABLE zones
    ADD CONSTRAINT fk_zones_primary_shelter
    FOREIGN KEY (primary_shelter_id)
    REFERENCES shelters (shelter_id)
    ON DELETE RESTRICT;

CREATE TABLE resource_categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    parent_id INTEGER,
    CONSTRAINT pk_resource_categories PRIMARY KEY (category_id),
    CONSTRAINT fk_resource_categories_parent
        FOREIGN KEY (parent_id)
        REFERENCES resource_categories (category_id)
        ON DELETE RESTRICT
);

CREATE TABLE resources (
    resource_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    category_id INTEGER NOT NULL,
    unit VARCHAR(20),
    CONSTRAINT pk_resources PRIMARY KEY (resource_id),
    CONSTRAINT fk_resources_category
        FOREIGN KEY (category_id)
        REFERENCES resource_categories (category_id)
        ON DELETE RESTRICT
);

CREATE TABLE shelter_inventory (
    shelter_id INTEGER NOT NULL,
    resource_id INTEGER NOT NULL,
    quantity INTEGER NOT NULL,
    reorder_level INTEGER NOT NULL DEFAULT 10,
    last_updated TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_shelter_inventory PRIMARY KEY (shelter_id, resource_id),
    CONSTRAINT fk_shelter_inventory_shelter
        FOREIGN KEY (shelter_id)
        REFERENCES shelters (shelter_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_shelter_inventory_resource
        FOREIGN KEY (resource_id)
        REFERENCES resources (resource_id)
        ON DELETE RESTRICT
);
