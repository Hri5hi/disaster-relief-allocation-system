-- ── 1. Table 15: app_users (Application Identity & RBAC) ───────────────────
CREATE TABLE app_users (
    user_id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    person_id           INTEGER NOT NULL,
    username            VARCHAR(50) NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    role                VARCHAR(30) NOT NULL,
    assigned_zone_id    INTEGER,
    is_active           BOOLEAN NOT NULL DEFAULT true,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_app_users PRIMARY KEY (user_id),
    CONSTRAINT uq_app_users_username UNIQUE (username),
    CONSTRAINT fk_app_users_person
        FOREIGN KEY (person_id)
        REFERENCES people (person_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_app_users_assigned_zone
        FOREIGN KEY (assigned_zone_id)
        REFERENCES zones (zone_id)
        ON DELETE SET NULL,
    CONSTRAINT chk_app_users_username_nonblank
        CHECK (btrim(username) <> ''),
    CONSTRAINT chk_app_users_role
        CHECK (role IN (
            'SYSTEM_ADMIN',
            'ZONE_COORDINATOR',
            'WAREHOUSE_MANAGER',
            'VOLUNTEER_COORDINATOR',
            'ANALYTICS_USER'
        )),
    CONSTRAINT chk_app_users_zone_coord_requires_zone
        CHECK (
            (role = 'ZONE_COORDINATOR' AND assigned_zone_id IS NOT NULL)
            OR (role <> 'ZONE_COORDINATOR')
        )
);

COMMENT ON TABLE app_users IS
    'Authentication and authorization support table linked to people, storing BCrypt credentials and RBAC roles.';

CREATE INDEX idx_app_users_person_id
    ON app_users (person_id);

CREATE INDEX idx_app_users_role
    ON app_users (role);

CREATE INDEX idx_app_users_assigned_zone
    ON app_users (assigned_zone_id);


-- ── 2. Row-Level Security (RLS) ─────────────────────────────────────────────
-- Scoped to app.current_zone_id, set per transaction by Database.inTransaction.

ALTER TABLE resource_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE affected_persons ENABLE ROW LEVEL SECURITY;
ALTER TABLE zones ENABLE ROW LEVEL SECURITY;

CREATE POLICY rls_resource_requests_policy ON resource_requests
    FOR ALL
    USING (
        NULLIF(current_setting('app.current_zone_id', true), '') IS NULL
        OR zone_id = NULLIF(current_setting('app.current_zone_id', true), '')::INTEGER
    )
    WITH CHECK (
        NULLIF(current_setting('app.current_zone_id', true), '') IS NULL
        OR zone_id = NULLIF(current_setting('app.current_zone_id', true), '')::INTEGER
    );

CREATE POLICY rls_zones_policy ON zones
    FOR ALL
    USING (
        NULLIF(current_setting('app.current_zone_id', true), '') IS NULL
        OR zone_id = NULLIF(current_setting('app.current_zone_id', true), '')::INTEGER
    );

CREATE POLICY rls_affected_persons_policy ON affected_persons
    FOR ALL
    USING (
        NULLIF(current_setting('app.current_zone_id', true), '') IS NULL
        OR shelter_id IS NULL
        OR shelter_id IN (
            SELECT s.shelter_id FROM shelters s
            JOIN zones z ON z.primary_shelter_id = s.shelter_id
            WHERE z.zone_id = NULLIF(current_setting('app.current_zone_id', true), '')::INTEGER
        )
    );


-- ── 3. Operational Views ────────────────────────────────────────────────────

-- View 1: v_shelter_dashboard
CREATE OR REPLACE VIEW v_shelter_dashboard AS
SELECT
    s.shelter_id,
    s.name AS shelter_name,
    s.address,
    s.capacity,
    s.current_occupancy,
    ROUND((s.current_occupancy::NUMERIC / NULLIF(s.capacity, 0)::NUMERIC) * 100, 2) AS occupancy_percentage,
    s.status,
    COALESCE(COUNT(DISTINCT si.resource_id), 0) AS distinct_resources_stocked,
    COALESCE(SUM(si.quantity), 0) AS total_resource_units
FROM shelters s
LEFT JOIN shelter_inventory si ON s.shelter_id = si.shelter_id
GROUP BY s.shelter_id, s.name, s.address, s.capacity, s.current_occupancy, s.status;

-- View 2: v_pending_requests_ranked
CREATE OR REPLACE VIEW v_pending_requests_ranked AS
SELECT
    r.request_id,
    r.zone_id,
    z.name AS zone_name,
    r.resource_id,
    res.name AS resource_name,
    r.destination_shelter_id,
    sh.name AS destination_shelter_name,
    r.quantity_requested,
    r.urgency,
    r.priority_score,
    r.status,
    r.requested_at
FROM resource_requests r
JOIN zones z ON r.zone_id = z.zone_id
JOIN resources res ON r.resource_id = res.resource_id
JOIN shelters sh ON r.destination_shelter_id = sh.shelter_id
WHERE r.status = 'pending'
ORDER BY r.priority_score DESC, r.requested_at ASC;

-- View 3: v_volunteer_availability
CREATE OR REPLACE VIEW v_volunteer_availability AS
SELECT
    v.person_id AS volunteer_id,
    p.name AS volunteer_name,
    p.contact,
    p.email,
    v.skills,
    v.availability,
    v.assigned_zone,
    z.name AS assigned_zone_name,
    COALESCE(COUNT(vs.shift_id), 0) AS active_shift_count
FROM volunteers v
JOIN people p ON v.person_id = p.person_id
LEFT JOIN zones z ON v.assigned_zone = z.zone_id
LEFT JOIN volunteer_shifts vs ON v.person_id = vs.volunteer_id
GROUP BY v.person_id, p.name, p.contact, p.email, v.skills, v.availability, v.assigned_zone, z.name;

-- View 4: v_active_disasters
CREATE OR REPLACE VIEW v_active_disasters AS
SELECT
    d.disaster_id,
    d.name AS disaster_name,
    d.type,
    d.severity,
    d.active_period,
    d.status,
    d.created_at,
    COUNT(DISTINCT z.zone_id) AS total_zones,
    COUNT(DISTINCT rr.request_id) FILTER (WHERE rr.status = 'pending') AS pending_requests_count
FROM disasters d
LEFT JOIN zones z ON d.disaster_id = z.disaster_id
LEFT JOIN resource_requests rr ON z.zone_id = rr.zone_id
WHERE d.status IN ('active'::disaster_status, 'monitoring'::disaster_status)
GROUP BY d.disaster_id, d.name, d.type, d.severity, d.active_period, d.status, d.created_at;


-- ── 4. Materialized Views ───────────────────────────────────────────────────

-- MV 1: mv_zone_resource_summary
CREATE MATERIALIZED VIEW mv_zone_resource_summary AS
SELECT
    z.zone_id,
    z.name AS zone_name,
    res.resource_id,
    res.name AS resource_name,
    COALESCE(SUM(rr.quantity_requested), 0)::BIGINT AS total_requested,
    COALESCE(SUM(CASE WHEN rr.status = 'fulfilled' THEN rr.quantity_requested ELSE 0 END), 0)::BIGINT AS total_allocated,
    COALESCE(SUM(CASE WHEN rr.status = 'pending' THEN rr.quantity_requested ELSE 0 END), 0)::BIGINT AS total_pending
FROM zones z
CROSS JOIN resources res
LEFT JOIN resource_requests rr ON z.zone_id = rr.zone_id AND res.resource_id = rr.resource_id
GROUP BY z.zone_id, z.name, res.resource_id, res.name;

CREATE UNIQUE INDEX idx_mv_zone_resource_summary_pk
    ON mv_zone_resource_summary (zone_id, resource_id);

-- MV 2: mv_daily_distribution_stats
CREATE MATERIALIZED VIEW mv_daily_distribution_stats AS
SELECT
    distributed_at::DATE AS distribution_date,
    resource_id,
    COUNT(*)::BIGINT AS transfer_count,
    SUM(quantity)::BIGINT AS total_quantity_distributed
FROM distribution_log
GROUP BY distributed_at::DATE, resource_id;

CREATE UNIQUE INDEX idx_mv_daily_dist_pk
    ON mv_daily_distribution_stats (distribution_date, resource_id);


-- ── 5. Stored Function: fn_zone_deficit_report ──────────────────────────────
-- Compares required resources from pending requests against available stock in primary shelters.

CREATE OR REPLACE FUNCTION fn_zone_deficit_report(p_disaster_id INTEGER)
RETURNS TABLE (
    zone_id         INTEGER,
    zone_name       VARCHAR(100),
    resource_id     INTEGER,
    resource_name   VARCHAR(100),
    required_qty    BIGINT,
    available_qty   BIGINT,
    deficit_qty     BIGINT,
    urgency_level   VARCHAR(10)
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    WITH zone_demand AS (
        SELECT
            rr.zone_id,
            rr.resource_id,
            COALESCE(SUM(rr.quantity_requested), 0)::BIGINT AS required_amount,
            MAX(CASE rr.urgency
                WHEN 'critical' THEN 4
                WHEN 'high' THEN 3
                WHEN 'medium' THEN 2
                WHEN 'low' THEN 1
                ELSE 0 END) AS max_urgency_val
        FROM resource_requests rr
        JOIN zones z ON rr.zone_id = z.zone_id
        WHERE z.disaster_id = p_disaster_id
          AND rr.status = 'pending'
        GROUP BY rr.zone_id, rr.resource_id
    ),
    zone_stock AS (
        SELECT
            z.zone_id,
            si.resource_id,
            COALESCE(SUM(si.quantity), 0)::BIGINT AS stock_amount
        FROM zones z
        LEFT JOIN shelters s ON s.shelter_id = z.primary_shelter_id
        LEFT JOIN shelter_inventory si ON si.shelter_id = s.shelter_id
        WHERE z.disaster_id = p_disaster_id
        GROUP BY z.zone_id, si.resource_id
    )
    SELECT
        z.zone_id,
        z.name AS zone_name,
        res.resource_id,
        res.name AS resource_name,
        COALESCE(zd.required_amount, 0)::BIGINT AS required_qty,
        COALESCE(zs.stock_amount, 0)::BIGINT AS available_qty,
        GREATEST(0, COALESCE(zd.required_amount, 0) - COALESCE(zs.stock_amount, 0))::BIGINT AS deficit_qty,
        CASE COALESCE(zd.max_urgency_val, 0)
            WHEN 4 THEN 'critical'::VARCHAR(10)
            WHEN 3 THEN 'high'::VARCHAR(10)
            WHEN 2 THEN 'medium'::VARCHAR(10)
            WHEN 1 THEN 'low'::VARCHAR(10)
            ELSE 'none'::VARCHAR(10)
        END AS urgency_level
    FROM zones z
    CROSS JOIN resources res
    LEFT JOIN zone_demand zd ON z.zone_id = zd.zone_id AND res.resource_id = zd.resource_id
    LEFT JOIN zone_stock zs ON z.zone_id = zs.zone_id AND res.resource_id = zs.resource_id
    WHERE z.disaster_id = p_disaster_id
      AND (COALESCE(zd.required_amount, 0) > 0 OR COALESCE(zs.stock_amount, 0) > 0)
    ORDER BY deficit_qty DESC, required_qty DESC;
END;
$$;

COMMENT ON FUNCTION fn_zone_deficit_report(INTEGER) IS
    'Returns resource demand, available primary shelter inventory, and net deficit per zone for a given disaster.';
