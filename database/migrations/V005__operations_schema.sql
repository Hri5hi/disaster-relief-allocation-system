-- ── Table 10: resource_requests ─────────────────────────────────────────────
CREATE TABLE resource_requests (
    request_id              INTEGER GENERATED BY DEFAULT AS IDENTITY,
    zone_id                 INTEGER NOT NULL,
    resource_id             INTEGER NOT NULL,
    destination_shelter_id  INTEGER NOT NULL,
    quantity_requested      INTEGER NOT NULL,
    urgency                 VARCHAR(10) NOT NULL,
    priority_score          INTEGER GENERATED ALWAYS AS (
        (CASE urgency
            WHEN 'critical' THEN 40
            WHEN 'high' THEN 30
            WHEN 'medium' THEN 20
            WHEN 'low' THEN 10
            ELSE 0
         END) + (quantity_requested / 10)
    ) STORED,
    status                  VARCHAR(20) NOT NULL DEFAULT 'pending',
    requested_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    fulfilled_at            TIMESTAMPTZ,
    CONSTRAINT pk_resource_requests PRIMARY KEY (request_id),
    CONSTRAINT fk_resource_requests_zone
        FOREIGN KEY (zone_id)
        REFERENCES zones (zone_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_resource_requests_resource
        FOREIGN KEY (resource_id)
        REFERENCES resources (resource_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_resource_requests_dest_shelter
        FOREIGN KEY (destination_shelter_id)
        REFERENCES shelters (shelter_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_resource_requests_quantity_positive
        CHECK (quantity_requested > 0),
    CONSTRAINT chk_resource_requests_urgency
        CHECK (urgency IN ('critical', 'high', 'medium', 'low')),
    CONSTRAINT chk_resource_requests_status
        CHECK (status IN ('pending', 'fulfilled', 'cancelled')),
    CONSTRAINT chk_resource_requests_fulfilled_state
        CHECK (
            (status = 'fulfilled' AND fulfilled_at IS NOT NULL)
            OR (status <> 'fulfilled')
        )
);

COMMENT ON TABLE resource_requests IS
    'Resource requests raised by zone coordinators, prioritized by Postgres generated column, and fulfilled by warehouse managers.';
COMMENT ON COLUMN resource_requests.destination_shelter_id IS
    'Specific relief shelter designated to receive the requested resource upon allocation.';
COMMENT ON COLUMN resource_requests.priority_score IS
    'Deterministic score generated from urgency weight and requested volume; Java never writes this column.';

CREATE INDEX idx_resource_requests_zone_id
    ON resource_requests (zone_id);

CREATE INDEX idx_resource_requests_resource_id
    ON resource_requests (resource_id);

CREATE INDEX idx_resource_requests_destination_shelter
    ON resource_requests (destination_shelter_id);

CREATE INDEX idx_resource_requests_status
    ON resource_requests (status);

CREATE INDEX idx_resource_requests_pending_priority
    ON resource_requests (priority_score DESC, requested_at ASC)
    WHERE status = 'pending';


-- ── Table 11: distribution_log (Range Partitioned) ──────────────────────────
CREATE TABLE distribution_log (
    log_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    source_shelter  INTEGER NOT NULL,
    dest_shelter    INTEGER NOT NULL,
    resource_id     INTEGER NOT NULL,
    quantity        INTEGER NOT NULL,
    distributed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_distribution_log PRIMARY KEY (log_id, distributed_at),
    CONSTRAINT fk_distribution_log_source
        FOREIGN KEY (source_shelter)
        REFERENCES shelters (shelter_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_distribution_log_dest
        FOREIGN KEY (dest_shelter)
        REFERENCES shelters (shelter_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_distribution_log_resource
        FOREIGN KEY (resource_id)
        REFERENCES resources (resource_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_distribution_log_quantity_positive
        CHECK (quantity > 0)
) PARTITION BY RANGE (distributed_at);

COMMENT ON TABLE distribution_log IS
    'Append-only historical log of inter-shelter transfers and fulfillment distributions, partitioned monthly.';
COMMENT ON COLUMN distribution_log.distributed_at IS
    'Partition key. Queries filtering by date range benefit from Postgres partition pruning.';

-- Initial range partitions: previous month, active month, next month, and default catch-all
CREATE TABLE distribution_log_2026_09 PARTITION OF distribution_log
    FOR VALUES FROM ('2026-09-01 00:00:00+00') TO ('2026-10-01 00:00:00+00');

CREATE TABLE distribution_log_2026_10 PARTITION OF distribution_log
    FOR VALUES FROM ('2026-10-01 00:00:00+00') TO ('2026-11-01 00:00:00+00');

CREATE TABLE distribution_log_2026_11 PARTITION OF distribution_log
    FOR VALUES FROM ('2026-11-01 00:00:00+00') TO ('2026-12-01 00:00:00+00');

CREATE TABLE distribution_log_default PARTITION OF distribution_log
    DEFAULT;

CREATE INDEX idx_distribution_log_source_shelter
    ON distribution_log (source_shelter);

CREATE INDEX idx_distribution_log_dest_shelter
    ON distribution_log (dest_shelter);

CREATE INDEX idx_distribution_log_resource_id
    ON distribution_log (resource_id);

CREATE INDEX idx_distribution_log_distributed_at
    ON distribution_log (distributed_at DESC);


-- ── Table 13: donation_records ──────────────────────────────────────────────
CREATE TABLE donation_records (
    donation_id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    donor_name          VARCHAR(100),
    items               JSONB NOT NULL,
    received_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    receiving_shelter   INTEGER,
    CONSTRAINT pk_donation_records PRIMARY KEY (donation_id),
    CONSTRAINT fk_donation_records_receiving_shelter
        FOREIGN KEY (receiving_shelter)
        REFERENCES shelters (shelter_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_donation_records_donor_nonblank
        CHECK (donor_name IS NULL OR btrim(donor_name) <> ''),
    CONSTRAINT chk_donation_records_items_array
        CHECK (jsonb_typeof(items) = 'array' AND jsonb_array_length(items) > 0)
);

COMMENT ON TABLE donation_records IS
    'Immutable intake log of donated resource bundles. Stored items JSONB array is atomically unpacked into shelter inventory by fn_process_donation.';

CREATE INDEX idx_donation_records_receiving_shelter
    ON donation_records (receiving_shelter);

CREATE INDEX idx_donation_records_received_at
    ON donation_records (received_at DESC);

CREATE INDEX idx_donation_records_items
    ON donation_records USING GIN (items);


-- ── Table 14: audit_log ─────────────────────────────────────────────────────
CREATE TABLE audit_log (
    log_id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    table_name      VARCHAR(50) NOT NULL,
    operation       VARCHAR(10) NOT NULL,
    old_values      JSONB,
    new_values      JSONB,
    changed_by      VARCHAR(100) DEFAULT CURRENT_USER,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_audit_log PRIMARY KEY (log_id),
    CONSTRAINT chk_audit_log_table_name_nonblank
        CHECK (btrim(table_name) <> ''),
    CONSTRAINT chk_audit_log_operation
        CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE'))
);

COMMENT ON TABLE audit_log IS
    'System-wide mutation audit log populated strictly by trg_audit_log on the 10 mutable tables. Never written directly by Java application code.';

CREATE INDEX idx_audit_log_table_operation
    ON audit_log (table_name, operation);

CREATE INDEX idx_audit_log_changed_at
    ON audit_log (changed_at DESC);

CREATE INDEX idx_audit_log_changed_by
    ON audit_log (changed_by);

CREATE INDEX idx_audit_log_old_values
    ON audit_log USING GIN (old_values);

CREATE INDEX idx_audit_log_new_values
    ON audit_log USING GIN (new_values);
